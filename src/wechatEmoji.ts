const EMOJI_PATTERN = /\[([^\[\]]{1,12})\]/g;

/** 把消息文本里的 "[微笑]" 之类替换成 emoji 字符。 */
export function replaceWechatEmoji(text: string): string {
  if (!text) return text;
  return text.replace(EMOJI_PATTERN, (match, name: string) => WECHAT_EMOJI[name] ?? match);
}
